import Foundation

/// Builds a checksum manifest from finished transfer items.
///
/// A manifest records one hash per file. During a copy the engine computes the **source**
/// checksum while reading, then (when verification is on) re-reads the **destination** from
/// disk and compares — a passing file therefore has an identical source and destination hash,
/// so the single value written represents both. The output is standard
/// `shasum`/`md5sum` format (or SFV for CRC-32) and can be checked later with those tools.
///
/// Files that **failed** verification are deliberately excluded: their destination does not
/// match the recorded hash, so listing them would assert a checksum the file on disk does not
/// have. The build result reports how many such files were left out so the caller can warn.
public enum ChecksumManifest {

    public struct BuildResult: Sendable {
        public let text: String
        public let includedCount: Int
        /// Files whose verification failed and were omitted from the manifest.
        public let excludedFailedCount: Int
        /// Files that were only source-hashed (verification was off) — included, but the
        /// destination was never read back, so the caller may want to note it.
        public let unverifiedCount: Int
    }

    /// Destination-relative path of an item, accounting for a keep-both rename.
    public static func manifestPath(for item: FileItem) -> String {
        guard let renamed = item.destinationName else { return item.relativePath }
        let parent = (item.relativePath as NSString).deletingLastPathComponent
        return parent.isEmpty ? renamed : parent + "/" + renamed
    }

    public static func build(from items: [FileItem], algorithm: HashAlgorithm) -> BuildResult {
        var lines: [String] = []
        var included = 0
        var excludedFailed = 0
        var unverified = 0

        let header = "# \(algorithm.rawValue) checksums generated by VeriCopy on "
            + ISO8601DateFormatter().string(from: Date())
        let commentPrefix = algorithm == .crc32 ? "; " : "# "
        lines.append(commentPrefix + header.dropFirst(2))

        for item in items {
            // A failed file carries the source hash but a known-bad destination — never list it.
            if item.status == .failed {
                if item.checksum != nil { excludedFailed += 1 }
                continue
            }
            guard let checksum = item.checksum else { continue } // pending / skipped / symlink
            if item.status == .doneNoVerify && !item.isSymlink { unverified += 1 }

            let path = manifestPath(for: item)
            if algorithm == .crc32 {
                lines.append("\(path) \(checksum)")          // SFV: name first
            } else {
                lines.append("\(checksum)  \(path)")          // shasum/md5sum: hash first, two spaces
            }
            included += 1
        }

        return BuildResult(text: lines.joined(separator: "\n") + "\n",
                           includedCount: included,
                           excludedFailedCount: excludedFailed,
                           unverifiedCount: unverified)
    }
}
